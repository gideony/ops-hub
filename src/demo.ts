function task(
  id: string,
  title: string,
  description: string,
  team_id: string,
  assignee_id: string,
  client_id: string | null,
  stage: number,
  priority: Task['priority'],
  due: number | null,
  tags: string[],
  completed_at: string | null = null,
  origin_task_id: string | null = null,
  root_task_id: string | null = null,
  forwarded_at: string | null = null,
  forwarded_by: string | null = null,
  board_id: string | null = 'board-geral-legado'
): Task {
  return {
    id,
    title,
    description,
    team_id,
    assignee_id,
    client_id,
    stage_id: `bstage-legado-${stage}`,
    priority,
    due_at: due === null ? null : isoOffset(due),
    tags,
    completed_at,
    created_by: demoUserId,
    created_at: now,
    updated_at: now,
    origin_task_id,
    root_task_id: root_task_id || id,
    forwarded_at,
    forwarded_by,
    board_id: board_id || 'board-geral-legado'
  }
}
